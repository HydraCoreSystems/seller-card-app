// Builds src/core/zipData.ts from the SimpleMaps Basic US ZIP Codes file (uszips.csv).
// Usage: node scripts/buildZipData.mjs path/to/uszips.csv
// Needs the columns zip, city, state_id. Rows marked military are skipped.
// Source: https://simplemaps.com/data/us-zips (Creative Commons Attribution 4.0).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const src = process.argv[2];
if (!src) {
  console.error('Usage: node scripts/buildZipData.mjs path/to/uszips.csv');
  process.exit(1);
}

function parseCsv(text) {
  const rows = [];
  let row = [], cell = '', quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { cell += '"'; i++; }
      else if (c === '"') quoted = false;
      else cell += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') { row.push(cell); cell = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(cell); cell = '';
      if (row.length > 1 || row[0] !== '') rows.push(row);
      row = [];
    } else cell += c;
  }
  if (cell !== '' || row.length) { row.push(cell); rows.push(row); }
  return rows;
}

const [head, ...body] = parseCsv(readFileSync(src, 'utf8').replace(/^﻿/, ''));
const col = (name) => {
  const i = head.indexOf(name);
  if (i < 0) throw new Error(`Missing column ${name}`);
  return i;
};
const iZip = col('zip'), iCity = col('city'), iState = col('state_id');
const iMil = head.indexOf('military');

const groups = new Map();
let count = 0;
for (const r of body) {
  if (iMil >= 0 && /^true$/i.test(r[iMil])) continue;
  const zip = r[iZip].trim().padStart(5, '0');
  if (!/^\d{5}$/.test(zip)) continue;
  const city = r[iCity].trim(), state = r[iState].trim();
  if (!city || !/^[A-Z]{2}$/.test(state) || /[|,\n]/.test(city)) throw new Error(`Bad row for ${zip}`);
  const key = `${state}|${city}`;
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(Number(zip));
  count++;
}

// One line per city: "ST|City|first,gap,gap" with every number in base 36, ZIPs sorted ascending.
const lines = [...groups.keys()].sort().map((key) => {
  const zips = groups.get(key).sort((a, b) => a - b);
  const nums = zips.map((z, i) => (i === 0 ? z : z - zips[i - 1]).toString(36));
  return `${key}|${nums.join(',')}`;
});

const out =
  `// Generated by scripts/buildZipData.mjs. Do not edit by hand.\n` +
  `// US ZIP code to city and state, ${count} ZIP codes. Data from SimpleMaps US ZIP Codes (Basic),\n` +
  `// https://simplemaps.com/data/us-zips, licensed under Creative Commons Attribution 4.0.\n` +
  `// One line per city: STATE|City|first ZIP, then the gap to each next ZIP, all in base 36.\n` +
  `export const ZIP_DATA_COUNT = ${count};\n` +
  `export const ZIP_DATA = ${JSON.stringify(lines.join('\n'))};\n`;
writeFileSync(fileURLToPath(new URL('../src/core/zipData.ts', import.meta.url)), out);
console.log(`${count} ZIP codes, ${lines.length} city lines, ${out.length} bytes`);
